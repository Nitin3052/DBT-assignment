USE NS;
SELECT MIN(STATUS)
FROM S;

SELECT MAX(WEIGHT)
FROM P;

SELECT AVG(WEIGHT)
FROM P;

SELECT SUM(QTY)
FROM SPJ
WHERE 'P#' = 'P1';

SELECT `P#`, SUM(QTY)
FROM SPJ
GROUP BY `P#`;

SELECT 'P#', AVG(QTY)
FROM SPJ;

SELECT 'P#', MAX(QTY)
FROM SPJ
GROUP BY 'P#'
HAVING MAX(QTY) > 800;

SELECT STATUS, COUNT(*)
FROM S
GROUP BY STATUS;

SELECT CITY, COUNT(*)
FROM J
GROUP BY CITY;
GROUP BY STATUS;